import { readFile, writeFile, stat } from 'node:fs/promises';
import { resolve, join } from 'node:path';
import { sign, verify, createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
const directory=resolve(process.argv[2]||'.jarvis/release-candidate');
const version=JSON.parse(await readFile('package.json','utf8')).version;
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version))throw Error('A stable release version is required.');
const commit=execFileSync('/usr/bin/git',['rev-parse','HEAD'],{encoding:'utf8'}).trim();
if(!/^[a-f0-9]{40}$/.test(commit))throw Error('Release source commit is required.');
if(execFileSync('/usr/bin/git',['status','--porcelain'],{encoding:'utf8'}).trim())throw Error('Release source must be clean and committed.');
const key=await readFile(resolve('.jarvis/private/release-signing/ed25519-private.pem'));
const config=await readFile('src/shared/release-config.ts','utf8');
const publicKey=JSON.parse(config.match(/releasePublicKey = (".*");/)?.[1]||'null');
if(!publicKey)throw Error('Pinned public release key is missing.');
const asset=async(name)=>{const p=join(directory,name),s=await stat(p);return {name,size:s.size,sha256:createHash('sha256').update(await readFile(p)).digest('hex')};};
const manifest={schema:1,repository:'sultandilaram/jarvis',version,commit,publishedAt:new Date().toISOString(),dataSchema:1,notes:await readFile(join(directory,'RELEASE-NOTES.txt'),'utf8'),assets:{macArm64:await asset(`JARVIS-macOS-AppleSilicon-${version}.zip`),android:await asset(`JARVIS-Android-${version}.apk`),macDmg:await asset(`JARVIS-macOS-AppleSilicon-${version}.dmg`)}};
if(manifest.notes.length>8000)throw Error('Release notes exceed limit.');
const bytes=Buffer.from(JSON.stringify(manifest,null,2)+'\n');
const signature=sign(null,bytes,key);
if(!verify(null,bytes,publicKey,signature))throw Error('Private release key does not match the app trust root.');
await writeFile(join(directory,'release.json'),bytes);await writeFile(join(directory,'release.sig'),signature);
console.log('Signed release metadata for '+version+' at '+commit+'. No private key is included.');
